"""
edge_ai/step1_intro.py
ก้าวที่ 1: ทำความเข้าใจภาพดิจิทัลและพื้นฐาน OpenCV
หัวข้อ:
1. ภาพในคอมพิวเตอร์คือ NumPy Array (ความสูง, ความกว้าง, ช่องสี)
2. ลำดับสีของ OpenCV คือ BGR (Blue, Green, Red) ไม่ใช่ RGB
3. พิกัดพิกเซล (x, y): แกน x แนวนอน, แกน y แนวตั้ง
"""

import cv2
import numpy as np
from pathlib import Path

# หา Path ของโฟลเดอร์ edge_ai เพื่อบันทึกรูป
CURRENT_DIR = Path(__file__).resolve().parent
OUTPUT_IMAGE = CURRENT_DIR / "my_first_beans.jpg"

print("=" * 60)
print("🎓 ก้าวที่ 1: ผ่าดูโครงสร้างภาพดิจิทัล (Digital Image Fundamentals)")
print("=" * 60)

# -------------------------------------------------------------
# 1. สร้างภาพจำลอง (Canvas)
# -------------------------------------------------------------
# ขนาด: สูง 300 พิกเซล, กว้าง 400 พิกเซล, 3 ช่องสี (BGR)
# ค่า 210 คือสีเทาอ่อน (สมมุติว่าเป็นถาดรองเมล็ดกาแฟสำหรับส่องกล้อง)
canvas = np.full((300, 400, 3), 210, dtype=np.uint8)

print(f"1. ขนาดเมทริกซ์ภาพ (Shape): {canvas.shape}")
print("   - ความสูง (Rows)   = 300 พิกเซล")
print("   - ความกว้าง (Cols) = 400 พิกเซล")
print("   - ช่องสี (Channels) = 3 (B, G, R)\n")

# -------------------------------------------------------------
# 2. ลองวาดเมล็ดกาแฟ 3 สถานะลงบนถาด
# -------------------------------------------------------------
# สังเกตการระบุสีใน OpenCV: (Blue, Green, Red) ค่าอยู่ระหว่าง 0 - 255

# เมล็ดที่ 1: เมล็ดกาแฟดิบ (Unripe) -> สีเขียวสด (B=30, G=180, R=40)
cv2.circle(canvas, center=(100, 150), radius=35, color=(30, 180, 40), thickness=-1)
cv2.putText(canvas, "Unripe", (70, 210), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (0, 100, 0), 2)

# เมล็ดที่ 2: เมล็ดกาแฟสุก (Ripe) -> สีแดงสด (B=30, G=30, R=220)
cv2.circle(canvas, center=(200, 150), radius=35, color=(30, 30, 220), thickness=-1)
cv2.putText(canvas, "Ripe", (180, 210), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (0, 0, 180), 2)

# เมล็ดที่ 3: เมล็ดกาแฟดำ/เน่า (Black Defect) -> สีดำมืด (B=25, G=25, R=25)
cv2.circle(canvas, center=(300, 150), radius=35, color=(25, 25, 25), thickness=-1)
cv2.putText(canvas, "Black", (280, 210), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (30, 30, 30), 2)

# -------------------------------------------------------------
# 3. ลองส่องดู "ค่าตัวเลขจริง" ของแต่ละพิกเซล (Pixel Inspection)
# -------------------------------------------------------------
# จำไว้ว่าใน NumPy เวลาเข้าถึงพิกเซลจะใช้ [y, x] (แถว, คอลัมน์)
unripe_pixel = canvas[150, 100]  # จุดกึ่งกลางเมล็ดดิบ
ripe_pixel   = canvas[150, 200]  # จุดกึ่งกลางเมล็ดสุก
black_pixel  = canvas[150, 300]  # จุดกึ่งกลางเมล็ดดำ
bg_pixel     = canvas[20, 20]    # พื้นหลังถาด

print("2. ค่าสีตัวเลขจริง [Blue, Green, Red] ของแต่ละจุด:")
print(f"   🟢 เมล็ดดิบ (Unripe) ที่พิกัด (x=100, y=150) : {unripe_pixel} -> ค่า Green สูงสุด!")
print(f"   🔴 เมล็ดสุก (Ripe)   ที่พิกัด (x=200, y=150) : {ripe_pixel}   -> ค่า Red สูงสุด!")
print(f"   ⚫ เมล็ดดำ (Black)  ที่พิกัด (x=300, y=150) : {black_pixel}   -> ค่ามืดใกล้ 0 ทั้ง 3 สี!")
print(f"   ⬜ พื้นหลัง (Tray)   ที่พิกัด (x=20,  y=20)  : {bg_pixel}   -> สีเทาสม่ำเสมอ\n")

# -------------------------------------------------------------
# 4. บันทึกเป็นไฟล์ภาพ
# -------------------------------------------------------------
cv2.imwrite(str(OUTPUT_IMAGE), canvas)
print(f"3. บันทึกไฟล์ภาพสำเร็จเรียบร้อยที่:")
print(f"   📁 {OUTPUT_IMAGE}")
print("=" * 60)
